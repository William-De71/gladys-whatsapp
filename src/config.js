// -----------------------------------------------------------------------------
// Configuration of the WhatsApp integration.
//
// Fields of the config_schema:
//   - `phone_number_id`        id of the WhatsApp business phone number in the
//                              Cloud API (WhatsApp → API Setup of the Meta app);
//   - `business_account_id`    id of the WhatsApp Business Account (WABA) that
//                              owns it: the integration registers its webhook
//                              there and reads the message templates;
//   - `access_token`           permanent token of a system user (a `secret`:
//                              never sent back to the UI, never logged);
//   - `verify_token`           the token Meta sends back when the webhook URL
//                              is verified: generated by the integration when
//                              empty, shown in the form to be pasted in Meta;
//   - `register_webhook`       register the Gladys Plus URL at Meta by itself;
//   - `fallback_template`      approved template (one body variable) used when
//                              a message leaves the 24-hour window;
//   - `fallback_template_language` its language code (en_US, fr, de, es…);
//   - `mark_as_read`           blue ticks on the messages Gladys received;
//   - `language`               language of the replies sent before a contact
//                              is linked: `auto` follows the language of the
//                              last widget request.
//
// Internal key, outside the config_schema (never shown in the UI):
//   - `last_language`          language of the last widget request.
// -----------------------------------------------------------------------------

import { isLanguage } from './i18n.js';

const AUTO_LANGUAGE = 'auto';
const INTERNAL_KEYS = { language: 'last_language' };
const DEFAULT_TEMPLATE_LANGUAGE = 'en_US';

const readString = (raw) => (typeof raw === 'string' ? raw.trim() : '');
// Ids of the Graph API are numbers; a copy with spaces still works.
const readId = (raw) => {
  const text = readString(typeof raw === 'number' ? String(raw) : raw).replace(/\s+/g, '');
  return /^\d{5,30}$/.test(text) ? text : '';
};

/**
 * @description Read a boolean field (the form can send strings).
 * @param {unknown} raw - The raw value.
 * @param {boolean} fallback - The default.
 * @returns {boolean} The value.
 */
function readBoolean(raw, fallback) {
  if (typeof raw === 'boolean') {
    return raw;
  }
  if (raw === 'true' || raw === '1' || raw === 1) {
    return true;
  }
  if (raw === 'false' || raw === '0' || raw === 0) {
    return false;
  }
  return fallback;
}

/**
 * @description The name of a message template: lowercase letters, digits and
 * underscores, as Meta stores it.
 * @param {unknown} raw - What the user typed.
 * @returns {string} The name, empty when it cannot be one.
 * @example
 * readTemplateName(' gladys_notification '); // -> 'gladys_notification'
 */
function readTemplateName(raw) {
  const text = readString(raw);
  return /^[a-z0-9_]{1,512}$/.test(text) ? text : '';
}

/**
 * @description A template language code (en, en_US, pt_BR, zh_Hant_HK…).
 * @param {unknown} raw - What the user typed.
 * @param {string} fallback - The code when empty or malformed.
 * @returns {string} The code.
 * @example
 * readTemplateLanguage('fr', 'en_US'); // -> 'fr'
 */
function readTemplateLanguage(raw, fallback = DEFAULT_TEMPLATE_LANGUAGE) {
  const text = readString(raw).replace('-', '_');
  return /^[a-z]{2,3}(_[A-Za-z]{2,4}){0,2}$/.test(text) ? text : fallback;
}

/**
 * @description Normalize the raw config object from the host API.
 * @param {object} [rawConfig] - The raw config values.
 * @returns {object} The config: `{ phoneNumberId, businessAccountId,
 * accessToken, verifyToken, registerWebhook, fallbackTemplate,
 * fallbackLanguage, markAsRead, language }`.
 * @example
 * normalizeConfig({ phone_number_id: '106540352242922', access_token: 'EAAG…' });
 */
function normalizeConfig(rawConfig = {}) {
  const config = rawConfig ?? {};
  return {
    phoneNumberId: readId(config.phone_number_id),
    businessAccountId: readId(config.business_account_id),
    // A secret is kept as typed (minus the spaces of a sloppy copy).
    accessToken: typeof config.access_token === 'string' ? config.access_token.trim() : '',
    verifyToken: readString(config.verify_token),
    registerWebhook: readBoolean(config.register_webhook, true),
    fallbackTemplate: readTemplateName(config.fallback_template),
    fallbackLanguage: readTemplateLanguage(config.fallback_template_language),
    markAsRead: readBoolean(config.mark_as_read, true),
    language: isLanguage(config.language) ? config.language : AUTO_LANGUAGE,
  };
}

/**
 * @description Whether messages can be sent.
 * @param {object} config - A normalized config.
 * @returns {boolean} True with a phone number id and a token.
 */
const isConfigured = (config) => Boolean(config.phoneNumberId && config.accessToken);

/**
 * @description Read the stored language of the last widget request.
 * @param {object} [rawConfig] - The raw config values.
 * @param {string} fallback - The language to keep when nothing valid is stored.
 * @returns {string} The language.
 * @example
 * readLanguage({ last_language: 'fr' }, 'en'); // -> 'fr'
 */
function readLanguage(rawConfig, fallback) {
  const language = (rawConfig ?? {})[INTERNAL_KEYS.language];
  return isLanguage(language) ? language : fallback;
}

/**
 * @description A phone number for logs: the country code and the last two
 * digits only.
 * @param {string} number - Digits.
 * @returns {string} '33•••••••78'.
 * @example
 * maskNumber('33612345678'); // -> '33•••••••78'
 */
function maskNumber(number) {
  const digits = String(number ?? '');
  if (digits.length <= 4) {
    return '•'.repeat(digits.length);
  }
  return `${digits.slice(0, 2)}${'•'.repeat(digits.length - 4)}${digits.slice(-2)}`;
}

/**
 * @description A recipient typed in a scene: an international number, with
 * or without +, 00, spaces, dots or dashes.
 * @param {unknown} raw - What the scene author typed.
 * @returns {string} The digits, empty when it cannot be a number.
 * @example
 * readPhoneNumber('+33 6 12 34 56 78'); // -> '33612345678'
 */
function readPhoneNumber(raw) {
  const text = readString(typeof raw === 'number' ? String(raw) : raw)
    .replace(/[\s().-]/g, '')
    .replace(/^\+/, '')
    .replace(/^00/, '');
  return /^\d{7,15}$/.test(text) ? text : '';
}

export {
  AUTO_LANGUAGE,
  INTERNAL_KEYS,
  DEFAULT_TEMPLATE_LANGUAGE,
  normalizeConfig,
  isConfigured,
  readLanguage,
  readTemplateName,
  readTemplateLanguage,
  readPhoneNumber,
  maskNumber,
};
